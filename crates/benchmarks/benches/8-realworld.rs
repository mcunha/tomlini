// ---- Benchmarks ----

#[divan::bench]
fn parse_cargo_tiny() -> tomlini::FlatDoc {
    tomlini::parse(CARGO_TINY).unwrap()
}

#[divan::bench]
fn parse_cargo_small() -> tomlini::FlatDoc {
    tomlini::parse(CARGO_SMALL).unwrap()
}

#[divan::bench]
fn parse_pyproject() -> tomlini::FlatDoc {
    tomlini::parse(PYPROJECT).unwrap()
}

#[divan::bench]
fn parse_cargo_lock() -> tomlini::FlatDoc {
    tomlini::parse(&CARGO_LOCK_TOML).unwrap()
}

#[divan::bench]
fn parse_alacritty() -> tomlini::FlatDoc {
    tomlini::parse(ALACRITTY_TOML).unwrap()
}

#[divan::bench]
fn edit_cargo_set_dep_version() -> String {
    let mut doc = tomlini::parse(CARGO_SMALL).unwrap();
    doc.edit()
        .set("dependencies.serde.version", "2")
        .commit()
        .unwrap();
    doc.to_string()
}

#[divan::bench]
fn edit_pyproject_add_dep() -> String {
    let mut doc = tomlini::parse(PYPROJECT).unwrap();
    doc.edit()
        .insert("project.dependencies", "toml", "\"0.8\"")
        .with_above_comment("Config file parsing")
        .commit()
        .unwrap();
    doc.to_string()
}

#[divan::bench]
fn edit_alacritty_change_theme() -> String {
    let mut doc = tomlini::parse(ALACRITTY_TOML).unwrap();
    let mut editor = tomlini::editor::Editor::new();
    editor
        .set("colors.primary.background", "\"#282828\"")
        .set("colors.primary.foreground", "\"#ebdbb2\"")
        .set("colors.normal.red", "\"#fb4934\"")
        .set("colors.normal.green", "\"#b8bb26\"");
    editor.commit(&mut doc).unwrap();
    doc.to_string()
}

#[divan::bench]
fn edit_cargo_lock_bump_version() -> String {
    let mut doc = tomlini::parse(&CARGO_LOCK_TOML).unwrap();
    doc.edit()
        .set("package.version", "4")
        .commit()
        .unwrap();
    doc.to_string()
}

// ---- INI cross-format benchmarks ----

#[divan::bench]
fn parse_cargo_lock_ini() -> tomlini::FlatDoc {
    tomlini::parse(&CARGO_LOCK_INI).unwrap()
}

#[divan::bench]
fn cross_format_roundtrip() -> usize {
    // Parse TOML, validate as Relaxed (INI), check error count
    let mut doc = tomlini::parse(&CARGO_LOCK_INI).unwrap();
    doc.validate(tomlini::ValidationMode::Relaxed).len()
}


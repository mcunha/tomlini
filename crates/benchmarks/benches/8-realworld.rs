/// Cargo.lock converted to TOML — dense, repetitive, many entries
static CARGO_LOCK_TOML: LazyLock<String> = LazyLock::new(|| {
    let mut s = String::with_capacity(60000);
    s.push_str("\
# This file is automatically generated\n\
version = 3\n\
\n\
");
    // 100 package entries
    for i in 0..100 {
        s.push_str(&format!("\
[[package]]\n\
name = \"crate-{i:03}\"\n\
version = \"{i}.{i%10}.{i%100}\"\n\
source = \"registry+https://github.com/rust-lang/crates.io-index\"\n\
checksum = \"sha256:deadbeef{i:04x}cafe\"\n\
dependencies = [\n\
    \"serde\",\n\
]\n\
\n\
"));
    }
    s.push_str("\
[[package]]\n\
name = \"my-root-crate\"\n\
version = \"1.0.0\"\n\
dependencies = [\n\
");
    for i in 0..100 {
        s.push_str(&format!("    \"crate-{i:03}\",\n"));
    }
    s.push_str("]\n");
    s
});

/// Cargo.lock converted to INI style — same data, different syntax
static CARGO_LOCK_INI: LazyLock<String> = LazyLock::new(|| {
    CARGO_LOCK_TOML.replace("[[package]]", "[package]").replace("dependencies = [", "dependencies = ").replace("]", "").replace("\"", "").replace(",", "")
});

